// Copies the Apache POI spreadsheet test files of at most 300 kB into tests/corpus/poi and
// lists each one in tests/corpus/LICENSES.md (docs/decisions.md D-901). Usage:
//   git clone --depth 1 --filter=blob:none --sparse https://github.com/apache/poi.git /tmp/poi
//   git -C /tmp/poi sparse-checkout set test-data/spreadsheet legal
//   node scripts/import-poi-corpus.mjs /tmp/poi
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { unzipSync } from 'fflate';

const MAX_BYTES = 300 * 1000;
const root = fileURLToPath(new URL('..', import.meta.url));
const poi = process.argv[2];
if (!poi) {
  console.error('Usage: node scripts/import-poi-corpus.mjs <path to an apache/poi checkout>');
  process.exit(2);
}
const commit = execFileSync('git', ['-C', poi, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
const source = join(poi, 'test-data/spreadsheet');
const target = join(root, 'tests/corpus/poi');
rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });
copyFileSync(join(poi, 'legal/LICENSE'), join(target, 'LICENSE'));
copyFileSync(join(poi, 'legal/NOTICE'), join(target, 'NOTICE'));

/** The application named in docProps/app.xml, if the file is a readable ZIP. */
function application(bytes) {
  try {
    const app = unzipSync(bytes, { filter: (f) => f.name === 'docProps/app.xml' })['docProps/app.xml'];
    const m = app && /<Application>([^<]*)<\/Application>/.exec(new TextDecoder().decode(app));
    return m ? m[1].replace(/\$.*/, '').replace(/\|/g, '/') : '';
  } catch {
    return '';
  }
}

const rows = [];
for (const name of readdirSync(source).filter((n) => /\.xlsx$/i.test(n)).sort()) {
  const size = statSync(join(source, name)).size;
  if (size > MAX_BYTES) continue;
  copyFileSync(join(source, name), join(target, name));
  const app = application(readFileSync(join(source, name)));
  rows.push(`| poi/${name} | Apache POI \`test-data/spreadsheet/${name}\` at commit ${commit.slice(0, 12)}${app ? `; written by ${app}` : ''} | Apache-2.0 |`);
}

const licensesPath = join(root, 'tests/corpus/LICENSES.md');
const begin = '<!-- poi:begin (generated by scripts/import-poi-corpus.mjs) -->';
const end = '<!-- poi:end -->';
const section = [
  begin,
  '',
  `### Apache POI test files (${rows.length} files)`,
  '',
  `Source: https://github.com/apache/poi, directory \`test-data/spreadsheet\`, commit ${commit}. License: Apache License 2.0, the license of the Apache POI repository (\`legal/LICENSE\`); \`tests/corpus/poi/LICENSE\` and \`tests/corpus/poi/NOTICE\` are copies of POI's \`legal/LICENSE\` and \`legal/NOTICE\`. Files larger than 300 kB were left out. The files are unchanged. "Written by" is the application named in the file's \`docProps/app.xml\`, where present.`,
  '',
  '| Path | Origin | License |',
  '|---|---|---|',
  ...rows,
  '',
  end,
].join('\n');
let licenses = readFileSync(licensesPath, 'utf8');
licenses = licenses.includes(begin) ? licenses.slice(0, licenses.indexOf(begin)) + section + licenses.slice(licenses.indexOf(end) + end.length) : `${licenses.trimEnd()}\n\n${section}\n`;
writeFileSync(licensesPath, licenses);
console.log(`Copied ${rows.length} files from ${commit}.`);
