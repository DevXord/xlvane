// Generates packages/xlvane/src/cli/east-asian-width.ts from the Unicode Character Database file
// EastAsianWidth.txt (F-UNICODE-01). Run by hand when the Unicode version changes; the tests never
// use the network. Usage:
//   node scripts/gen-east-asian-width.mjs path/to/EastAsianWidth.txt
// The file of Unicode 17.0.0 is unicodetools/data/ucd/17.0.0/EastAsianWidth.txt in
// github.com/unicode-org/unicodetools (the same file as www.unicode.org/Public/17.0.0/ucd/).
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const source = process.argv[2];
if (!source) {
  console.error('usage: node scripts/gen-east-asian-width.mjs path/to/EastAsianWidth.txt');
  process.exit(2);
}
const text = readFileSync(source, 'utf8');
const version = /^# EastAsianWidth-(\d+\.\d+\.\d+)\.txt/.exec(text)?.[1];
if (!version) throw new Error('The first line must name the file, such as "# EastAsianWidth-17.0.0.txt".');
const sha256 = createHash('sha256').update(text).digest('hex');

// Unassigned code points in these blocks and planes default to W (the header of the file).
const ranges = [
  [0x3400, 0x4dbf],
  [0x4e00, 0x9fff],
  [0xf900, 0xfaff],
  [0x20000, 0x2fffd],
  [0x30000, 0x3fffd],
];
for (const line of text.split('\n')) {
  const m = /^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*(W|F)\b/.exec(line);
  if (m) ranges.push([parseInt(m[1], 16), parseInt(m[2] ?? m[1], 16)]);
}
ranges.sort((a, b) => a[0] - b[0]);
const merged = [];
for (const [start, end] of ranges) {
  const last = merged[merged.length - 1];
  if (last && start <= last[1] + 1) last[1] = Math.max(last[1], end);
  else merged.push([start, end]);
}

const hex = (n) => `0x${n.toString(16)}`;
const rows = [];
for (let i = 0; i < merged.length; i += 6) rows.push(`  ${merged.slice(i, i + 6).map(([s, e]) => `${hex(s)}, ${hex(e)}`).join(', ')},`);
const out = `// Generated by scripts/gen-east-asian-width.mjs from EastAsianWidth-${version}.txt
// (sha256 ${sha256}; F-UNICODE-01). Do not edit by hand.

/**
 * Code points whose East_Asian_Width is Wide (W) or Fullwidth (F), including the unassigned code
 * points that default to W, as sorted pairs of first and last code point. Unicode ${version}.
 */
export const EAST_ASIAN_WIDE: readonly number[] = [
${rows.join('\n')}
];
`;
const target = fileURLToPath(new URL('../packages/xlvane/src/cli/east-asian-width.ts', import.meta.url));
writeFileSync(target, out);
console.log(`${target}: ${String(merged.length)} ranges from Unicode ${version}.`);
