// Parses the Shared String Table part (ECMA-376 Part 1 §12.3.15, §18.4; facts F-SST-01 …
// F-SST-07, decisions D-SST-1 … D-SST-4 in the facts file).
//
// The part can be large, so it is processed with the event parser and never built as a tree.
// Structure (sml.xsd CT_Sst, CT_Rst, CT_RElt, CT_PhoneticRun; identical in Strict and
// Transitional): sst > si* ; si > t?, r*, rPh*, phoneticPr? ; r > rPr?, t ; rPh > t.
// - The value of an si is the text of its own t followed by the t of each rich text run r
//   (§18.4.8 si, §18.4.4 r), in document order.
// - Phonetic runs (rPh, §18.4.6) are pronunciation hints shown above the base text; their text
//   is not part of the value (decision D-SST-2).
// - Each t is ST_Xstring (§18.4.12) and is decoded on its own, after XML references are expanded.
// - White space in t is kept as written whatever xml:space says: an XML processor passes all
//   character data to the application (XML 1.0 §2.10) and keeping it is always acceptable.
// - sst@count and sst@uniqueCount are not used; nothing is allocated from them.
import { XlvError } from '../errors';
import type { ReadLimits } from '../limits';
import type { WarningCollector } from '../util/warnings';
import { parseXml } from '../xml/parser';
import { SML_NS } from './namespaces';
import { decodeXstring } from './xstring';

/** What a part parser needs: the part name for locations, the limits and a warning sink. */
export interface PartContext {
  readonly part: string;
  readonly limits: ReadLimits;
  readonly warnings: WarningCollector;
}

// Depths of the elements we read: sst = 1, si = 2, t or r in si = 3, t in r = 4.
const SI_DEPTH = 2;
const ITEM_CHILD_DEPTH = 3;
const RUN_TEXT_DEPTH = 4;

/**
 * Parses the shared strings part and returns the plain text of every string item (`si`), in
 * order, so that index `i` is the value of a cell with `t="s"` and `<v>i</v>`.
 * Throws `XLV_E_PART_INVALID` if the root element is not `sst` in a SpreadsheetML namespace,
 * and the XML parser's errors for malformed XML.
 */
export function parseSharedStrings(xml: string, ctx: PartContext): string[] {
  const strings: string[] = [];
  let ns = '';
  let depth = 0;
  let inItem = false;
  let inRun = false;
  /** Depth of the open t element whose text is collected, or 0. */
  let textDepth = 0;
  let item: string[] = [];
  let raw: string[] = [];

  parseXml(
    xml,
    {
      start(elementNs, local) {
        depth++;
        if (depth === 1) {
          if (local !== 'sst' || (elementNs !== SML_NS.strict && elementNs !== SML_NS.transitional)) {
            throw new XlvError(
              'XLV_E_PART_INVALID',
              `The shared strings part has the root element <${local}> in namespace "${elementNs}"; expected <sst> in the SpreadsheetML namespace.`,
              {
                location: { part: ctx.part },
                hint: 'The part the workbook names as its shared string table is not one. Re-save the file in a spreadsheet application; if it was generated by a program, report the problem to its authors.',
                details: { element: local, namespace: elementNs },
              },
            );
          }
          ns = elementNs;
          return;
        }
        if (elementNs !== ns) return;
        if (depth === SI_DEPTH) {
          if (local === 'si') {
            inItem = true;
            item = [];
          }
          return;
        }
        if (!inItem) return;
        if (depth === ITEM_CHILD_DEPTH) {
          if (local === 't') textDepth = depth;
          else if (local === 'r') inRun = true;
        } else if (depth === RUN_TEXT_DEPTH && inRun && local === 't') {
          textDepth = depth;
        }
      },
      end() {
        if (textDepth !== 0 && depth === textDepth) {
          item.push(decodeXstring(raw.length === 1 ? (raw[0] ?? '') : raw.join('')));
          raw = [];
          textDepth = 0;
        } else if (depth === ITEM_CHILD_DEPTH) {
          inRun = false;
        } else if (depth === SI_DEPTH && inItem) {
          strings.push(item.length === 1 ? (item[0] ?? '') : item.join(''));
          inItem = false;
        }
        depth--;
      },
      text(value) {
        if (textDepth !== 0 && depth === textDepth) raw.push(value);
      },
    },
    ctx,
  );
  return strings;
}
